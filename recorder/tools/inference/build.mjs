import { build } from 'esbuild';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const output = fileURLToPath(new URL('../../lib/schema-validator.js', import.meta.url));
const license = await readFile(new URL('./VALIDATOR-LICENSE', import.meta.url), 'utf8');
const result = await build({
  entryPoints: [fileURLToPath(new URL('./validator-entry.mjs', import.meta.url))],
  bundle: true, minify: true, platform: 'browser', format: 'iife', target: 'chrome120',
  legalComments: 'inline', write: false,
  banner: { js: '// Generated by recorder/tools/inference/build.mjs. @cfworker/json-schema 4.1.6. Do not edit.\n/*\n' + license.trim() + '\n*/' },
});
const bytes = result.outputFiles[0].contents;
if (process.argv.includes('--check')) {
  const previous = await readFile(output);
  if (!previous.equals(Buffer.from(bytes))) throw new Error('schema-validator.js is stale; run npm run build');
} else await writeFile(output, bytes);
